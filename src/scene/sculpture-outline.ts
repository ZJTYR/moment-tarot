function contains(polygon: Outline, x: number, y: number) {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const a = polygon[i]; const b = polygon[j];
    if ((a[1] > y) !== (b[1] > y) && x < (b[0] - a[0]) * (y - a[1]) / (b[1] - a[1]) + a[0]) inside = !inside;
  }
  return inside;
}

export function sculptureContains(name: string, x: number, y: number): boolean | undefined {
  if (name === 'devil') return contains(devil, x, y);
  if (name === 'devil-back') return contains(devilBack, x, y);
  if (name === 'angel-back') return contains(angelBack, x, y);
  if (name === 'goddess-back') return contains(goddessBack, x, y) || contains(goddessOrb, x, y);
  return undefined;
}
