/** 输入必须是按过去、现在、未来排列的三张不同牌；无随机数或外部服务。 */
export function buildReading(cards: TarotCard[]): Reading {
  if (cards.length !== 3) throw new RangeError('完整解读需要按过去、现在、未来排列的三张牌。');
  if (new Set(cards.map(card => card.id)).size !== 3) throw new RangeError('三张牌不能重复。');
  const rules = cards.map(card => {
    if (!Object.hasOwn(RULES, card.id)) throw new RangeError(`暂不支持这张牌：${card.id}`);
    return RULES[card.id];
  });
  const [past, present, future] = rules;
  if (cards.map(card => card.id).join('/') === 'moon/death/judgement') {
    return {
      headline: '先确认事实，再换掉无效旧法，用一次小行动检验。',
      explanation: '过去的月亮提醒你回看哪些担心只是猜测；现在的死神提示检查反复无效的做法；未来的审判给出下一步：根据反馈试一次调整。三张牌连起来，是先弄清为什么，再决定改哪里。',
      example: '假如一份方案发出后没人回复，先问对方是没时间看，还是有具体顾虑；确认后停止反复催问或盲目重写，只改一个有反馈的部分，再请对方看看是否解决了问题。',
      action: '今天先发一句：“这份方案你方便看了吗？如果有顾虑，最需要我说明的是哪一点？”拿到原因后，再决定要不要修改。',
      quote: '有用的改变，从问清原因开始。',
    };
  }
  return {
    headline: `先${past.lesson}，${present.focus}，再${future.next}。`,
    explanation: `过去的「${cards[0].name}」提醒先${past.lesson}；有了这层判断，现在的「${cards[1].name}」建议${present.focus}；未来的「${cards[2].name}」再把它推进一步：${future.next}。`,
    example: `${present.scenario}。${past.check}${present.solution}${future.review}`,
    action: `今天${present.step}${future.review}`,
    quote: future.quote,
  };
}
